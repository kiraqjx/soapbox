export const FAMILY_LABEL = SCENE_FAMILIES.reduce((acc, item) => {
  acc[item.id] = item
  return acc
}, {})

const FAMILY_KEYWORDS = [
  ['ceremony', /主持|致辞|颁奖|婚礼|毕业|送别|开场白|串场/],
  ['defense', /答辩|面试|评审问答|竞标答疑|晋升/],
  ['pitch', /提案|路演|立项|商务|方案评审|竞标/],
  ['share', /分享|沙龙|复盘|方法论|读书|学习/],
  ['talk', /演讲|宣讲|发布|大会|TED|年会发言/],
]

export function inferFamily(sceneType = '') {
  for (const [id, re] of FAMILY_KEYWORDS) {
    if (re.test(sceneType)) return id
  }
  return 'report'
}

export function familyOf(profile) {
  const id = profile?.sceneFamily
  if (id && FAMILY_LABEL[id]) return id
  return inferFamily(profile?.sceneType || '')
}

export function familyName(id) {
  return FAMILY_LABEL[id]?.name || '向上汇报'
}

export function charsPerMinute(family) {
  switch (family) {
    case 'talk':
      return 200
    case 'share':
      return 220
    case 'ceremony':
      return 180
    default:
      return 240
  }
}

export function familyRules(family, profile = {}) {
  const base = [
    '不编造数字、人名、日期与案例；缺失处标注「（待补充）」并说明需要什么。',
    '输出可直接朗读的口语稿：短句、主动语态、每段不超过三句，不使用 Markdown 符号。',
  ]
  const taboos = String(profile.taboos || '')
    .split(/[,，、;；\s]+/)
    .map((s) => s.trim())
    .filter(Boolean)
  if (taboos.length) base.push(`避免使用这些词：${taboos.join('、')}。`)
  if (profile.habit) base.push(`讲述者自述的短板：${profile.habit}。请主动规避。`)

  const spec = {
    report: [
      '结构：结论先行 → 依据与数据 → 风险 → 明确请求 → 下一步时间点。',
      '每 30 秒要有一个可被记住的数字或判断，避免只讲过程。',
      '结尾必须给出一个二选一的决策请求。',
    ],
    talk: [
      '结构：15 秒钩子 → 为什么是我 → 三个观点 → 转折 → 金句收尾。',
      '开场不要客套铺垫，第一句就要制造好奇或冲突。',
      '每个观点配一个具体场景或一个人物，避免连续抽象论述。',
      '结尾留一句可以被引用、可以被转述的话。',
    ],
    share: [
      '结构：自我介绍与承诺 → 问题 → 方法框架 → 案例与踩坑 → 可带走清单。',
      '必须给出可复用的步骤或模板，并讲清适用边界。',
      '开头 30 秒告诉听众「听完能得到什么」。',
    ],
    pitch: [
      '结构：一句话价值主张 → 对方现状与代价 → 方案 → 证据 → 下一步。',
      '先讲对方的问题，不要先讲自己的公司。',
      '结尾给出低风险、可执行的第一步。',
    ],
    defense: [
      '用 STAR 讲案例：情境、任务、行动、结果，结果要量化。',
      '主动讲一处不足和改进动作，显示判断力。',
      '结尾留一个有价值的问题反问对方。',
    ],
    ceremony: [
      '称呼与礼节到位；感谢要具体到人和事。',
      '控制时长，不抢主角；短句、停顿、留白。',
      '结尾给一句具体祝福或一句清晰的宣布。',
    ],
  }
  return [...base, ...(spec[family] || spec.report)]
}
